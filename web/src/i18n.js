export function translator(lang) {
  const table = STRINGS[lang] || STRINGS.el;
  return (key, vars) => {
    let text = table[key] ?? STRINGS.el[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, v);
    return text;
  };
}
